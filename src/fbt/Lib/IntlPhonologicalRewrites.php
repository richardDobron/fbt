    private const DEFAULT_LOCALE = 'en_US';

    /**
     * @param string|null $localeTag
     *
     * @return array{meta: array<string, string>, patterns: array<string, string>}
     */
    public static function get(?string $localeTag): array
    {
        $key = $localeTag === null ? self::DEFAULT_LOCALE : $localeTag;
        $rewrites = self::REWRITES[$key] ?? self::EMPTY_REWRITES;

        return [
            'meta' => array_merge($rewrites['meta'], self::GLOBAL_REWRITES['meta']),
            'patterns' => array_merge($rewrites['patterns'], self::GLOBAL_REWRITES['patterns']),
        ];
    }
